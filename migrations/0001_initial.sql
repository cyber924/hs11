PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY,
 email TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL,
 password_hash TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
 id TEXT PRIMARY KEY,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS deals (
 id TEXT PRIMARY KEY,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL,
 sector TEXT NOT NULL DEFAULT '기타',
 stage TEXT NOT NULL DEFAULT '검토중',
 location TEXT NOT NULL DEFAULT '',
 sponsor TEXT NOT NULL DEFAULT '',
 amount REAL NOT NULL DEFAULT 0,
 currency TEXT NOT NULL DEFAULT 'USD',
 description TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL,
 updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS risks (
 id TEXT PRIMARY KEY,
 deal_id TEXT NOT NULL REFERENCES deals(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 category TEXT NOT NULL,
 title TEXT NOT NULL,
 likelihood INTEGER NOT NULL DEFAULT 3,
 impact INTEGER NOT NULL DEFAULT 3,
 mitigation TEXT NOT NULL DEFAULT '',
 owner TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS memos (
 id TEXT PRIMARY KEY,
 deal_id TEXT NOT NULL REFERENCES deals(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title TEXT NOT NULL,
 content TEXT NOT NULL DEFAULT '',
 updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS deals_user_updated ON deals(user_id,updated_at DESC);
CREATE INDEX IF NOT EXISTS risks_deal ON risks(deal_id);
CREATE INDEX IF NOT EXISTS memos_deal ON memos(deal_id);
